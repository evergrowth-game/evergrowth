"""Generate OBJ mesh models for eg_settlers job blocks."""

import os

MODEL_DIR = "/Users/Aresh/Desktop/Projects/evergrowth/mods/eg_settlers/models"


def generate_obj(filename, parts):
    lines = []
    lines.append("# Generated by generate_job_block_models.py")

    vertex_index = 1
    all_groups = []

    for mat_name, boxes in parts:
        faces_for_mat = []
        for box in boxes:
            x1, y1, z1, x2, y2, z2 = box
            lines.append(f"v {x1} {y1} {z1}")
            lines.append(f"v {x2} {y1} {z1}")
            lines.append(f"v {x2} {y2} {z1}")
            lines.append(f"v {x1} {y2} {z1}")
            lines.append(f"v {x1} {y1} {z2}")
            lines.append(f"v {x2} {y1} {z2}")
            lines.append(f"v {x2} {y2} {z2}")
            lines.append(f"v {x1} {y2} {z2}")

            vi = vertex_index
            faces_for_mat.extend([
                (vi+0, vi+1, vi+2, vi+3),
                (vi+5, vi+4, vi+7, vi+6),
                (vi+4, vi+0, vi+3, vi+7),
                (vi+1, vi+5, vi+6, vi+2),
                (vi+3, vi+2, vi+6, vi+7),
                (vi+4, vi+5, vi+1, vi+0),
            ])
            vertex_index += 8
        all_groups.append((mat_name, faces_for_mat))

    lines.append("vt 0 1")
    lines.append("vt 1 1")
    lines.append("vt 1 0")
    lines.append("vt 0 0")

    for mat_name, faces in all_groups:
        lines.append("")
        lines.append(f"usemtl {mat_name}")
        lines.append(f"g {mat_name.lower()}_group")
        for a, b, c, d in faces:
            lines.append(f"f {a}/1 {b}/2 {c}/3 {d}/4")

    lines.append("")

    filepath = os.path.join(MODEL_DIR, filename)
    with open(filepath, "w") as f:
        f.write("\n".join(lines))
    total_verts = (vertex_index - 1)
    total_faces = sum(len(g[1]) for g in all_groups)
    print(f"  {filename}: {total_verts} verts, {total_faces} faces")


